"""
SYNTHIA File Writer Tool — Phase 2
Saves research reports with rich metadata and formatting.
In Phase 5, this becomes a registered MCP server tool.
"""

import os
from datetime import datetime


def save_report(title: str, content: str) -> tuple[str, str]:
    """
    Save a completed research report to the outputs/ folder.

    Args:
        title: Report title
        content: Full markdown report content

    Returns:
        Tuple of (status message, file path)
    """
    os.makedirs("outputs", exist_ok=True)

    safe_title = "".join(c if c.isalnum() or c in " -_" else "" for c in title)
    safe_title = safe_title.strip().replace(" ", "_").lower()[:60]
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"outputs/{safe_title}_{timestamp}.md"

    metadata = f"""---
title: "{title}"
generated_by: SYNTHIA — Autonomous AI Research Agent
model: Claude (Anthropic)
date: {datetime.now().strftime("%B %d, %Y at %H:%M")}
phase: 2
---

"""

    footer = """

---
*This report was autonomously generated by SYNTHIA — an agentic AI research assistant built with the Anthropic Claude API, featuring multi-step tool use, search memory, and structured report synthesis.*

*GitHub: https://github.com/Ma107399/autoresearch-agent*
"""

    full_content = metadata + content + footer

    with open(filename, "w", encoding="utf-8") as f:
        f.write(full_content)

    return f"Report saved to {filename}", filename
