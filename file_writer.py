"""
File writer tool — saves research reports as markdown files.
In Phase 5, this becomes an MCP server tool exposed to the agent.
"""

import os
from datetime import datetime


def save_report(title: str, content: str) -> tuple[str, str]:
    """
    Save a research report to the outputs folder.

    Args:
        title: Report title (used for filename)
        content: Full markdown content

    Returns:
        Tuple of (status message, file path)
    """
    os.makedirs("outputs", exist_ok=True)

    # Clean title for filename
    safe_title = "".join(c if c.isalnum() or c in " -_" else "" for c in title)
    safe_title = safe_title.replace(" ", "_").lower()[:50]
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"outputs/{safe_title}_{timestamp}.md"

    # Add metadata header
    full_content = f"""# {title}

> **Generated by AutoResearch Agent**
> Date: {datetime.now().strftime("%B %d, %Y %H:%M")}
> Model: Claude (Anthropic)

---

{content}

---
*Report generated autonomously by AutoResearch — an agentic AI research assistant built with the Anthropic API.*
"""

    with open(filename, "w", encoding="utf-8") as f:
        f.write(full_content)

    return f"Report saved successfully to {filename}", filename
